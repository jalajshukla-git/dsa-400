// Regenerates the LeetCode indexes used for search + plan cross-linking.
//
//   node tools/build-lc-index.mjs            → fetches the live LeetCode index
//   node tools/build-lc-index.mjs lc.json    → uses a cached API dump
//
// Outputs:
//   src/lib/lc-titles.js   full index: number → [title, slug]   (all LeetCode problems)
//   src/lib/lc-plan.js     plan map: number → [{day, idx, title}] for EVERY
//                          LeetCode-linked question in the 400-day plan.
//
// Run this weekly (or whenever LeetCode adds problems / the plan changes):
//   npm run update:lc
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

async function loadLcIndex() {
  // 1) explicit file argument  2) cached dump  3) live fetch
  if (process.argv[2]) {
    return JSON.parse(fs.readFileSync(path.resolve(process.argv[2]), 'utf8'));
  }
  const cachePath = '/tmp/lc.json';
  if (fs.existsSync(cachePath)) {
    try { return JSON.parse(fs.readFileSync(cachePath, 'utf8')); } catch {}
  }
  console.log('Fetching https://leetcode.com/api/problems/all/ …');
  const res = await fetch('https://leetcode.com/api/problems/all/');
  if (!res.ok) throw new Error('LC API failed: HTTP ' + res.status);
  const json = await res.json();
  try { fs.writeFileSync(cachePath, JSON.stringify(json)); } catch {}
  return json;
}

const norm = t => String(t || '').toLowerCase().replace(/[^a-z0-9]/g, '');

async function main() {
  const raw = await loadLcIndex();
  const pairs = (raw.stat_status_pairs || [])
    .filter(p => p.stat && p.stat.frontend_question_id && p.stat.question__title && p.stat.question__title_slug)
    .sort((a, b) => a.stat.frontend_question_id - b.stat.frontend_question_id);

  // number → [title, slug]
  const numMap = {};
  const slugNum = {};
  const titleNum = {};
  for (const p of pairs) {
    const { frontend_question_id: n, question__title: t, question__title_slug: s } = p.stat;
    numMap[n] = [t, s];
    slugNum[s.toLowerCase()] = n;
    titleNum[norm(t)] = n;
  }

  // ── write src/lib/lc-titles.js ──
  const numBody = pairs.map(p => `${p.stat.frontend_question_id}:[${JSON.stringify(p.stat.question__title)},${JSON.stringify(p.stat.question__title_slug)}]`).join(',');
  const titlesSrc =
`// Auto-generated by tools/build-lc-index.mjs from https://leetcode.com/api/problems/all/
// number → [title, slug] for EVERY LeetCode problem (${pairs.length}).
export const LC_NUM = {${numBody}};
export const lcInfo = n => { const v = LC_NUM[n]; return v ? { n, t: v[0], slug: v[1], url: "https://leetcode.com/problems/" + v[1] + "/" } : null; };
`;
  fs.writeFileSync(path.join(ROOT, 'src/lib/lc-titles.js'), titlesSrc);

  // ── build the complete plan map ──
  const { TRACKER_DATA: data } = await import(pathToFileURL(path.join(ROOT, 'src/lib/tracker-data.js')).href);

  const lcToDays = {}; // number → [{day, idx, title}]
  const add = (n, d, idx, title) => {
    (lcToDays[n] = lcToDays[n] || []).push({ day: d.id, idx, title });
  };
  let viaUrl = 0, viaTitle = 0;
  for (const d of data.days) {
    d.items.forEach((it, idx) => {
      if (it.u) {
        const m = it.u.match(/leetcode\.com\/problems\/([a-z0-9-]+)/i);
        if (m && slugNum[m[1].toLowerCase()]) { add(slugNum[m[1].toLowerCase()], d, idx, it.n); viaUrl++; return; }
      }
      const n = titleNum[norm(it.n)];
      if (n) { add(n, d, idx, it.n); viaTitle++; }
    });
  }
  const planBody = Object.keys(lcToDays).map(k => `${k}:[${lcToDays[k].map(h => `{day:${h.day},idx:${h.idx},title:${JSON.stringify(h.title)}}`).join(',')}]`).join(',');
  const planSrc =
`// Auto-generated by tools/build-lc-index.mjs — complete plan cross-reference.
// number → [{day, idx, title}] for EVERY LeetCode-linked question in the 400-day plan.
export const LC_TO_DAYS = {${planBody}};
export const LC_TO_DAYS_COUNT = Object.keys(LC_TO_DAYS).length;
`;
  fs.writeFileSync(path.join(ROOT, 'src/lib/lc-plan.js'), planSrc);

  console.log(`lc-titles.js → ${pairs.length} problems`);
  console.log(`lc-plan.js    → ${Object.keys(lcToDays).length} distinct numbers, ${viaUrl + viaTitle} plan links (url:${viaUrl}, title:${viaTitle})`);
}

main().catch(e => { console.error(e); process.exit(1); });
